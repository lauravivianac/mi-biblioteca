/** "~320" -> 320. Las páginas vienen como texto aproximado. */
export function pageCount(pages) {
  const n = parseInt(String(pages ?? '').replace(/[^0-9]/g, ''), 10);
  return Number.isFinite(n) && n > 0 ? n : null;
}

